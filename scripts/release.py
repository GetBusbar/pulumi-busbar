"""Build provider assets and publish the generated Go SDK without moving tags."""
import argparse
import gzip
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tempfile


ROOT = Path(__file__).resolve().parents[1]
TARGETS = [(system, arch) for system in ("linux", "darwin", "windows")
           for arch in ("amd64", "arm64")]


class ReleaseError(ValueError):
    """An expected refusal, reported to the operator without a traceback."""


def run(*args, cwd=None, env=None, quiet=False):
    # stderr is captured so callers can classify failures; it is still shown
    # unless the caller handles an expected failure itself (quiet=True).
    try:
        result = subprocess.run(args, cwd=cwd or ROOT, env=env, text=True,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    except FileNotFoundError:
        raise ReleaseError(f"{args[0]} is not installed or not on PATH") from None
    if not quiet:
        sys.stderr.write(result.stderr)
    if result.returncode:
        raise subprocess.CalledProcessError(result.returncode, args, result.stdout, result.stderr)
    return result.stdout.strip()


def validate_version(version):
    # The checked-in module has no /vN suffix. A major release needs a module
    # migration first; never publish an unusable sdk/v2 tag for this module.
    if not re.fullmatch(r"[01]\.(?:0|[1-9][0-9]*)\.(?:0|[1-9][0-9]*)", version):
        raise ReleaseError("release requires a stable v0/v1 version matching sdk/go.mod")
    return version


def go_version_declaration(version):
    return f'var SdkVersion semver.Version = semver.MustParse("{version}")'


def archive_name(version, system, arch):
    return f"pulumi-resource-busbar-v{version}-{system}-{arch}.tar.gz"


# Provider inputs that must match the root tag exactly. The embedded schema is
# regenerated by `make build` and published with the SDK commit (publish_sdk).
PROVIDER_SOURCES = ["provider", "LICENSE",
                    ":(exclude)provider/cmd/pulumi-resource-busbar/schema-embed.json"]


def require_release_head(version):
    """Release artifacts must come from the commit of the immutable root tag."""
    try:
        source = run("git", "rev-parse", f"refs/tags/v{version}^{{commit}}", quiet=True)
    except subprocess.CalledProcessError as error:
        detail = (error.stderr or "").strip() or f"git exited {error.returncode}"
        raise ReleaseError(f"missing root release tag v{version}: {detail}") from None
    if source != run("git", "rev-parse", "HEAD"):
        raise ReleaseError("release artifacts must be built at the immutable root release tag")
    return source


def require_remote_root_tag(version):
    """The published root tag must exist and be the local root tag; gh/git never create one."""
    tag = "v" + version
    remote = run("git", "ls-remote", "origin", f"refs/tags/{tag}")
    if not remote:
        raise ReleaseError(f"missing remote root tag {tag}")
    if remote.split()[0] != run("git", "rev-parse", f"refs/tags/{tag}"):
        raise ReleaseError(f"remote {tag} is not the local root release tag")


def prepare(version):
    validate_version(version)
    require_release_head(version)
    # Python's generator already respects the schema version. Reject stale
    # generation rather than silently publish a different package version.
    # Read and validate everything before writing so a rejected run leaves no partial edit.
    setup = (ROOT / "sdk/python/setup.py").read_text()
    if f'VERSION = "{version}"' not in setup:
        raise ReleaseError("Python SDK was not generated with the release version")
    go_path = ROOT / "sdk/go/busbar/internal/pulumiVersion.go"
    go_source, count = re.subn(r"var SdkVersion semver.Version = [^\n]+",
                               go_version_declaration(version), go_path.read_text())
    if count != 1:
        raise ReleaseError("unrecognized generated Go SDK version declaration")
    edits = {go_path: go_source}
    for relative, indent in (("sdk/nodejs/package.json", 4),
                             ("sdk/python/pulumi_busbar/pulumi-plugin.json", 2),
                             ("sdk/go/busbar/pulumi-plugin.json", 2)):
        path = ROOT / relative
        manifest = json.loads(path.read_text())
        manifest["version"] = version
        edits[path] = json.dumps(manifest, indent=indent) + "\n"
    for path, contents in edits.items():
        path.write_text(contents)


def archives(version, destination):
    validate_version(version)
    require_release_head(version)
    # go build reads the working tree, so also refuse edits git status hides:
    # assume-unchanged/skip-worktree entries and ignored Go files. Vendored
    # modules are ignored by the -mod=readonly build below.
    changed = run("git", "status", "--porcelain", "--untracked-files=normal", "--",
                  *PROVIDER_SOURCES).splitlines()
    changed += [line for line in run("git", "ls-files", "-v", "--", *PROVIDER_SOURCES).splitlines()
                if line[:1].islower() or line[:1] == "S"]
    changed += run("git", "ls-files", "--others", "--ignored", "--exclude-standard", "--",
                   "provider/*.go", ":(exclude,glob)provider/**/vendor/**").splitlines()
    if changed:
        raise ReleaseError("provider sources differ from the root tag; build from a clean tag "
                           "checkout: " + ", ".join(line.strip() for line in changed))
    destination = Path(destination).resolve()
    destination.mkdir(parents=True, exist_ok=True)
    # A stale checksum file must never survive a failed rebuild.
    (destination / "SHA256SUMS").unlink(missing_ok=True)
    checksums = []
    with tempfile.TemporaryDirectory(prefix="busbar-release-") as directory:
        for system, arch in TARGETS:
            name = "pulumi-resource-busbar" + (".exe" if system == "windows" else "")
            binary = Path(directory) / name
            # Build only from go.mod/go.sum: ignore any go.work and vendor directory.
            env = dict(os.environ, GOOS=system, GOARCH=arch, CGO_ENABLED="0", GOWORK="off")
            run("go", "build", "-trimpath", "-buildvcs=false", "-mod=readonly", "-o", str(binary), "-ldflags",
                "-s -w -X github.com/getbusbar/pulumi-busbar/provider/pkg/version.Version=" + version,
                "./cmd/pulumi-resource-busbar", cwd=ROOT / "provider", env=env)
            archive = destination / archive_name(version, system, arch)
            with archive.open("wb") as raw, gzip.GzipFile(fileobj=raw, mode="wb", filename="", mtime=0) as zipped:
                with tarfile.open(fileobj=zipped, mode="w") as output:
                    for path, member_name in ((binary, name), (ROOT / "LICENSE", "LICENSE")):
                        info = output.gettarinfo(path, arcname=member_name)
                        info.uid = info.gid = info.mtime = 0
                        info.uname = info.gname = ""
                        info.mode = 0o644 if member_name == "LICENSE" else 0o755
                        with path.open("rb") as contents:
                            output.addfile(info, contents)
            checksums.append(f"{hashlib.sha256(archive.read_bytes()).hexdigest()}  {archive.name}\n")
    (destination / "SHA256SUMS").write_text("".join(checksums))


def publish_sdk(version):
    validate_version(version)
    source = require_release_head(version)
    require_remote_root_tag(version)
    stamped = [json.loads((ROOT / relative).read_text()).get("version") for relative in (
        "sdk/nodejs/package.json", "sdk/python/pulumi_busbar/pulumi-plugin.json",
        "sdk/go/busbar/pulumi-plugin.json")]
    if stamped != [version] * 3 or go_version_declaration(version) not in (
            ROOT / "sdk/go/busbar/internal/pulumiVersion.go").read_text():
        raise ReleaseError("run prepare before publishing the SDK")
    # An isolated index includes only generated SDKs/schema, never build output
    # or unrelated staged changes. A deterministic commit makes retries safe.
    with tempfile.TemporaryDirectory(prefix="busbar-sdk-index-") as directory:
        env = dict(os.environ, GIT_INDEX_FILE=str(Path(directory) / "index"))
        run("git", "read-tree", source, env=env)
        run("git", "add", "sdk", "provider/cmd/pulumi-resource-busbar/schema-embed.json", env=env)
        # The tag is public and immutable: publish only modifications of files
        # at the root tag, never added, renamed or deleted files (credentials,
        # venvs, scratch files, stale generation).
        changed = run("git", "diff", "--cached", "--no-renames", "--name-only", "--diff-filter=m",
                      source, env=env)
        if changed:
            raise ReleaseError("files added or removed relative to the root tag (remove them, or "
                               "commit regenerated SDKs and check `make drift`): "
                               + ", ".join(changed.split("\n")))
        tree = run("git", "write-tree", env=env)
    date = run("git", "show", "-s", "--format=%cI", source)
    env = dict(os.environ, GIT_AUTHOR_NAME="github-actions[bot]",
               GIT_AUTHOR_EMAIL="41898282+github-actions[bot]@users.noreply.github.com",
               GIT_COMMITTER_NAME="github-actions[bot]",
               GIT_COMMITTER_EMAIL="41898282+github-actions[bot]@users.noreply.github.com",
               GIT_AUTHOR_DATE=date, GIT_COMMITTER_DATE=date)
    commit = run("git", "commit-tree", tree, "-p", source,
                 "-m", f"Release generated SDK v{version}", env=env)
    tag = f"refs/tags/sdk/v{version}"
    existing = run("git", "ls-remote", "origin", tag)
    if existing:
        # The tag is pushed as a lightweight tag, so its remote id is the commit.
        if existing.split()[0] != commit:
            raise ReleaseError(f"refusing to replace existing sdk/v{version}")
    else:
        # A simultaneous publisher can only make this fail; no force update.
        run("git", "push", "origin", f"{commit}:{tag}")
    print(f"sdk/v{version}: {commit}")


def publish_provider(version, destination):
    validate_version(version)
    destination = Path(destination).resolve()
    archive_names = [archive_name(version, system, arch) for system, arch in TARGETS]
    names = archive_names + ["SHA256SUMS"]
    for name in names:
        if not (destination / name).is_file():
            raise ReleaseError(f"missing release asset: {name}")
    # Publish only archives that SHA256SUMS describes exactly.
    expected = "".join(f"{hashlib.sha256((destination / name).read_bytes()).hexdigest()}  {name}\n"
                       for name in archive_names)
    if (destination / "SHA256SUMS").read_text() != expected:
        raise ReleaseError("SHA256SUMS does not match the provider archives; rerun archives")
    tag = "v" + version
    require_release_head(version)
    # Verify the remote root tag; gh must never implicitly create one.
    require_remote_root_tag(version)
    try:
        release = json.loads(run("gh", "release", "view", tag, "--json", "assets,isDraft", quiet=True))
    except subprocess.CalledProcessError as error:
        if "release not found" not in (error.stderr or ""):
            sys.stderr.write(error.stderr or "")
            raise
        run("gh", "release", "create", tag, "--verify-tag", "--draft",
            "--title", tag, "--notes", f"Busbar Pulumi provider and SDKs {tag}.")
        release = {"assets": [], "isDraft": True}
    existing = {asset["name"] for asset in release["assets"]}
    # Publishing the draft would expose every asset on it, so allow only ours.
    unexpected = sorted(existing - set(names))
    if unexpected:
        raise ReleaseError(f"release {tag} has unexpected assets: " + ", ".join(unexpected))
    # Never clobber assets on a retry. Byte differences require investigation.
    with tempfile.TemporaryDirectory(prefix="busbar-release-assets-") as directory:
        for name in names:
            if name in existing:
                run("gh", "release", "download", tag, "--pattern", name, "--dir", directory)
                if (Path(directory) / name).read_bytes() != (destination / name).read_bytes():
                    raise ReleaseError(f"refusing to replace existing release asset {name}")
            else:
                run("gh", "release", "upload", tag, str(destination / name))
    if release["isDraft"]:
        run("gh", "release", "edit", tag, "--draft=false")


def version_argument(version):
    try:
        return validate_version(version)
    except ValueError as error:
        raise argparse.ArgumentTypeError(f"{error} (got {version!r})") from None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["validate", "prepare", "archives", "publish-sdk", "publish-provider"])
    parser.add_argument("version", type=version_argument)
    parser.add_argument("--destination", default="dist/provider")
    args = parser.parse_args()
    try:
        if args.action == "prepare":
            prepare(args.version)
        elif args.action == "archives":
            archives(args.version, args.destination)
        elif args.action == "publish-sdk":
            publish_sdk(args.version)
        elif args.action == "publish-provider":
            publish_provider(args.version, args.destination)
    except ReleaseError as error:
        # Expected refusals are messages for the operator, not crashes.
        parser.exit(1, f"release.py: error: {error}\n")


if __name__ == "__main__":
    main()
